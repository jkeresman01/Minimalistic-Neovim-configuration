##############################################################################
#
# Check if a package argument was provided
#
##############################################################################
pkg="$1"

[ -n "$pkg" ] || {
echo "Usage: godocf <package>"
exit 1
}

##############################################################################
#
# List package documentation entries and let the user select a function
# using fzf, with a live documentation preview
#

##############################################################################
fn=$(go doc "$pkg" |
awk -F '(' '{print $1}' |
awk '{print $2}' |
fzf --preview "go doc '$pkg'.{}") || exit 0

##############################################################################
#
# Display the full documentation for the selected function
#
##############################################################################
[ -n "$fn" ] && go doc "$pkg.$fn"

